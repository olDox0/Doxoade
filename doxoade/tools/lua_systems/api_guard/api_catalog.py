@dataclass
class APIEntry:
    id: str                                # Ex: "RootView.on_text_input" ou "core.open_doc"
    kind: str                              # "module" | "class" | "method" | "function" | "field" | "event_handler"
    module: str                            # Ex: "core.rootview", "core", "system"
    name: str                              # Ex: "on_text_input"
    expected_type: str = "function"        # "function" | "table" | "string" | "number" | "boolean"
    cls_name: Optional[str] = None         # Ex: "RootView", "Doc", "Node"
    severity_if_missing: str = "critical"  # "critical" | "warning" | "info"
    safe_to_patch: bool = False            # Se o Doxoade pode aplicar monkey-patch com segurança
    is_deprecated: bool = False            # Se a API é obsoleta/deprecada em versões novas
    fallback: Optional[str] = None         # Nome ou estratégia de fallback (ex: "Doc.text_input")
    signature_notes: str = ""              # Detalhes de argumentos e retornos esperados
    known_consumers: List[str] = field(default_factory=list)  # Quais templates utilizam

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> APIEntry:
        valid_keys = {k for k in cls.__dataclass_fields__}
        filtered = {k: v for k, v in data.items() if k in valid_keys}
        return cls(**filtered)


class APICatalogSchema:
    """Serializador e validador de integridade do catálogo."""

    SCHEMA_VERSION = "2.0.0"

    @classmethod
    def serialize_json(cls, catalog: Dict[str, APIEntry], indent: int = 2) -> str:
        payload = {
            "version": cls.SCHEMA_VERSION,
            "total_entries": len(catalog),
            "apis": {k: v.to_dict() for k, v in sorted(catalog.items())}
        }
        return json.dumps(payload, indent=indent, ensure_ascii=False)

    @classmethod
    def deserialize_json(cls, json_str: str) -> Dict[str, APIEntry]:
        data = json.loads(json_str)
        apis: Dict[str, APIEntry] = {}
        for k, v in data.get("apis", {}).items():
            apis[k] = APIEntry.from_dict(v)
        return apis

    @classmethod
    def export_to_lua(cls, catalog: Dict[str, APIEntry]) -> str:
        """Gera uma tabela Lua soberana consumível diretamente por api_probe e api_guard."""
        def to_lua_val(val: Any) -> str:
            if val is None:
                return "nil"
            elif isinstance(val, bool):
                return "true" if val else "false"
            elif isinstance(val, (int, float)):
                return str(val)
            else:
                return json.dumps(str(val))

        lines = [
            "-- auto-generated by doxoade api_catalog.py",
            "return {",
            f'  schema_version = "{cls.SCHEMA_VERSION}",',
            f"  total_apis = {len(catalog)},",
            "  catalog = {"
        ]
        for api_id, entry in sorted(catalog.items()):
            lines.append(f'    ["{api_id}"] = {{')
            lines.append(f'      kind = "{entry.kind}",')
            lines.append(f'      module = "{entry.module}",')
            lines.append(f'      name = "{entry.name}",')
            lines.append(f'      expected_type = "{entry.expected_type}",')
            lines.append(f'      cls_name = {to_lua_val(entry.cls_name)},')
            lines.append(f'      severity = "{entry.severity_if_missing}",')
            lines.append(f'      safe_to_patch = {"true" if entry.safe_to_patch else "false"},')
            lines.append(f'      is_deprecated = {"true" if entry.is_deprecated else "false"},')
            lines.append(f'      fallback = {to_lua_val(entry.fallback)},')
            lines.append("    },")
        lines.append("  }")
        lines.append("}")
        return "\n".join(lines)


def get_api_guard_dir(user_dir: Optional[Path] = None) -> Path:
    """Retorna e garante o diretório padrão de artefatos do API Guard."""
    if user_dir is None:
        try:
            from doxoade.commands.lite_xl_systems.engine_lite_xl import LiteXLEngine
            user_dir = LiteXLEngine.get_user_dir()
        except Exception:
            user_dir = Path.home() / ".config" / "lite-xl"

    guard_dir = user_dir / ".doxoade" / "api_guard"
    guard_dir.mkdir(parents=True, exist_ok=True)
    (guard_dir / "reports").mkdir(exist_ok=True)
    (guard_dir / "quarantine").mkdir(exist_ok=True)
    return guard_dir

