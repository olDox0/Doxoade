def load_catalog(path: Optional[Union[str, Path]] = None) -> Dict[str, APIEntry]:
    """Carrega o catálogo do disco ou retorna o semente caso não exista."""
    if path is None:
        target = get_api_guard_dir() / "catalog.json"
    else:
        target = Path(path)

    if target.exists() and target.is_file():
        try:
            return APICatalogSchema.deserialize_json(target.read_text(encoding="utf-8"))
        except Exception:
            return get_default_catalog()
    return get_default_catalog()


def save_catalog(catalog: Dict[str, APIEntry], path: Optional[Union[str, Path]] = None) -> Path:
    """Salva o catálogo em JSON e exporta a versão correspondente para Lua."""
    if path is None:
        guard_dir = get_api_guard_dir()
        target_json = guard_dir / "catalog.json"
        target_lua = guard_dir / "catalog.lua"
    else:
        target_json = Path(path)
        target_lua = target_json.with_suffix(".lua")

    target_json.parent.mkdir(parents=True, exist_ok=True)
    target_json.write_text(APICatalogSchema.serialize_json(catalog), encoding="utf-8")
    target_lua.write_text(APICatalogSchema.export_to_lua(catalog), encoding="utf-8")
    return target_json


def get_api_entry(catalog: Dict[str, APIEntry], api_id: str) -> Optional[APIEntry]:
    """Consulta uma entrada no catálogo por ID."""
    return catalog.get(api_id)


def list_critical_apis(catalog: Dict[str, APIEntry]) -> List[APIEntry]:
    """Filtra apenas as APIs com severidade crítica."""
    return [e for e in catalog.values() if e.severity_if_missing == "critical"]
